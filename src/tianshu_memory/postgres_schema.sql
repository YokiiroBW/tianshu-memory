-- Memory/Knowledge PostgreSQL schema. Product-owned, with no business data.

CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS people (id TEXT PRIMARY KEY);

CREATE TABLE IF NOT EXISTS accounts (
  account_key TEXT PRIMARY KEY, person_id TEXT NOT NULL REFERENCES people(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, display_name TEXT);

CREATE TABLE IF NOT EXISTS scopes (key TEXT PRIMARY KEY, version BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS requests (
  service TEXT NOT NULL, operation TEXT NOT NULL, key TEXT NOT NULL,
  digest TEXT NOT NULL, result TEXT NOT NULL, PRIMARY KEY(service,operation,key));

CREATE TABLE IF NOT EXISTS sources (
  key TEXT PRIMARY KEY, revision BIGINT NOT NULL, epoch BIGINT NOT NULL,
  state TEXT NOT NULL, scope TEXT NOT NULL, reality TEXT NOT NULL, payload TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS groups (
  id TEXT PRIMARY KEY, scope TEXT NOT NULL, state TEXT NOT NULL, members TEXT NOT NULL,
  category TEXT NOT NULL, field_key TEXT, item_key TEXT);

CREATE INDEX IF NOT EXISTS groups_scope ON groups(scope,state,category);

CREATE INDEX IF NOT EXISTS groups_field ON groups(scope,field_key,state,category);

CREATE INDEX IF NOT EXISTS groups_item ON groups(scope,item_key,state,category);

CREATE TABLE IF NOT EXISTS records (
  id TEXT PRIMARY KEY, group_id TEXT NOT NULL REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, state TEXT NOT NULL, payload TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS records_group ON records(group_id);

CREATE TABLE IF NOT EXISTS history (
  record_id TEXT NOT NULL, version BIGINT NOT NULL, state TEXT NOT NULL,
  payload TEXT NOT NULL, PRIMARY KEY(record_id,version));

CREATE TABLE IF NOT EXISTS lineage (
  group_id TEXT NOT NULL REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE, source_key TEXT NOT NULL REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE,
  revision BIGINT NOT NULL, epoch BIGINT NOT NULL,
  PRIMARY KEY(group_id,source_key));

CREATE TABLE IF NOT EXISTS projections (
  ref TEXT PRIMARY KEY, record_id TEXT NOT NULL REFERENCES records(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, state TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS confirmations (
  ref TEXT PRIMARY KEY, digest TEXT NOT NULL, account_key TEXT NOT NULL,
  scope TEXT NOT NULL, expires_at TEXT NOT NULL, consumed BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS inbox (
  event_id TEXT PRIMARY KEY, digest TEXT NOT NULL, result TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS turn_inputs (
  turn_id TEXT NOT NULL, revision BIGINT NOT NULL, digest TEXT NOT NULL,
  result TEXT NOT NULL, PRIMARY KEY(turn_id,revision));

CREATE TABLE IF NOT EXISTS aggregate_events (
  owner TEXT NOT NULL, aggregate_id TEXT NOT NULL, version BIGINT NOT NULL,
  digest TEXT NOT NULL, PRIMARY KEY(owner,aggregate_id,version));

CREATE TABLE IF NOT EXISTS conflicts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, operation TEXT NOT NULL,
  request_id TEXT NOT NULL, digest TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS jobs (
  id TEXT PRIMARY KEY, state TEXT NOT NULL, event TEXT NOT NULL, source_snapshot TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS write_ledger (
  job_id TEXT PRIMARY KEY REFERENCES jobs(id) DEFERRABLE INITIALLY IMMEDIATE, digest TEXT NOT NULL, result TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS source_writes (
  source_key TEXT NOT NULL, revision BIGINT NOT NULL, scope TEXT NOT NULL,
  job_id TEXT NOT NULL, PRIMARY KEY(source_key,revision,scope));

CREATE TABLE IF NOT EXISTS relationship_entries (
  group_id TEXT PRIMARY KEY REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE, amount BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS outbox (
  position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL, payload TEXT NOT NULL, acknowledged BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS search_index (record_id TEXT, record_version BIGINT, scope TEXT, text TEXT);

CREATE INDEX IF NOT EXISTS search_index_terms ON search_index USING gin(to_tsvector('simple',text));

CREATE TABLE IF NOT EXISTS profile_shares (
  group_id TEXT PRIMARY KEY REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE, actor_id TEXT NOT NULL,
  subject_kind TEXT NOT NULL, subject_id TEXT NOT NULL, sharing TEXT NOT NULL,
  conversation_id TEXT, approval_ref TEXT NOT NULL UNIQUE);

CREATE INDEX IF NOT EXISTS profile_audience ON profile_shares(
  actor_id,subject_kind,subject_id,sharing,conversation_id);

CREATE TABLE IF NOT EXISTS profile_approvals (
  ref TEXT PRIMARY KEY, digest TEXT NOT NULL, source_snapshot TEXT NOT NULL,
  expires_at TEXT NOT NULL, consumed BIGINT NOT NULL DEFAULT 0, result TEXT);

CREATE TABLE IF NOT EXISTS physical_sources (
  key TEXT PRIMARY KEY, payload TEXT, revision BIGINT NOT NULL, state TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS source_admissions (
  key TEXT PRIMARY KEY REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE, physical_key TEXT NOT NULL REFERENCES physical_sources(key) DEFERRABLE INITIALLY IMMEDIATE,
  actor_id TEXT NOT NULL, selector TEXT NOT NULL UNIQUE, payload TEXT, verified BIGINT NOT NULL DEFAULT 0);

CREATE INDEX IF NOT EXISTS admissions_physical ON source_admissions(physical_key);

CREATE TABLE IF NOT EXISTS suppression (source_key TEXT PRIMARY KEY REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE, reason TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS owner_heads (owner TEXT PRIMARY KEY, generation TEXT NOT NULL, sequence BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS source_observations (
  kind TEXT NOT NULL, key TEXT NOT NULL, sequence BIGINT NOT NULL, payload TEXT NOT NULL,
  PRIMARY KEY(kind,key));

ALTER TABLE confirmations ADD COLUMN IF NOT EXISTS binding_version BIGINT;

ALTER TABLE confirmations ADD COLUMN IF NOT EXISTS record_id TEXT;

ALTER TABLE confirmations ADD COLUMN IF NOT EXISTS expected_version BIGINT;

CREATE TABLE IF NOT EXISTS knowledge_projects (id TEXT PRIMARY KEY, registration TEXT NOT NULL,
  revision BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS knowledge_documents (id TEXT PRIMARY KEY, project_id TEXT
  REFERENCES knowledge_projects(id) DEFERRABLE INITIALLY IMMEDIATE, source_id TEXT NOT NULL UNIQUE, kind TEXT NOT NULL,
  locator TEXT NOT NULL, version BIGINT NOT NULL, state TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS knowledge_versions (document_id TEXT NOT NULL REFERENCES knowledge_documents(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, hash TEXT NOT NULL, raw TEXT NOT NULL, text TEXT NOT NULL,
  media_type TEXT NOT NULL, provenance TEXT NOT NULL, PRIMARY KEY(document_id,version));

CREATE TABLE IF NOT EXISTS knowledge_blocks (id TEXT PRIMARY KEY, document_id TEXT NOT NULL,
  version BIGINT NOT NULL, payload TEXT NOT NULL,
  FOREIGN KEY(document_id,version) REFERENCES knowledge_versions(document_id,version) DEFERRABLE INITIALLY IMMEDIATE);

CREATE TABLE IF NOT EXISTS knowledge_states (project_id TEXT PRIMARY KEY REFERENCES knowledge_projects(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, payload TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS knowledge_state_history (project_id TEXT NOT NULL REFERENCES knowledge_projects(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(project_id,version));

CREATE TABLE IF NOT EXISTS knowledge_operations (client TEXT NOT NULL, key TEXT NOT NULL, digest TEXT NOT NULL,
  result TEXT NOT NULL, PRIMARY KEY(client,key));

CREATE TABLE IF NOT EXISTS knowledge_imports (client TEXT NOT NULL, key TEXT NOT NULL, project_id TEXT NOT NULL,
  status TEXT NOT NULL, result TEXT NOT NULL, PRIMARY KEY(client,key));

CREATE TABLE IF NOT EXISTS knowledge_index (block_id TEXT, project_id TEXT, text TEXT);

CREATE INDEX IF NOT EXISTS knowledge_index_terms ON knowledge_index USING gin(to_tsvector('simple',text));

CREATE TABLE IF NOT EXISTS knowledge_content_documents (document_id TEXT PRIMARY KEY REFERENCES knowledge_documents(id) DEFERRABLE INITIALLY IMMEDIATE,
 owner TEXT NOT NULL, metadata TEXT NOT NULL, access_version BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS knowledge_content_grants (document_id TEXT NOT NULL REFERENCES knowledge_documents(id) DEFERRABLE INITIALLY IMMEDIATE,
 reader TEXT NOT NULL, version BIGINT NOT NULL, hash TEXT NOT NULL, enabled BIGINT NOT NULL,
 PRIMARY KEY(document_id,reader));

CREATE TABLE IF NOT EXISTS knowledge_content_uploads (id TEXT PRIMARY KEY, owner TEXT NOT NULL, descriptor TEXT NOT NULL,
 raw TEXT, state TEXT NOT NULL, expires_at TEXT NOT NULL, document_id TEXT REFERENCES knowledge_documents(id) DEFERRABLE INITIALLY IMMEDIATE);

CREATE TABLE IF NOT EXISTS knowledge_content_operations (owner TEXT NOT NULL, operation TEXT NOT NULL, request_id TEXT NOT NULL,
 digest TEXT NOT NULL, result TEXT NOT NULL, PRIMARY KEY(owner,operation,request_id));

CREATE TABLE IF NOT EXISTS lessons (id TEXT PRIMARY KEY, project_id TEXT NOT NULL REFERENCES knowledge_projects(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, state TEXT NOT NULL, payload TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS lessons_project ON lessons(project_id,state);

CREATE TABLE IF NOT EXISTS lesson_history (lesson_id TEXT NOT NULL, version BIGINT NOT NULL,
  payload TEXT NOT NULL, PRIMARY KEY(lesson_id,version));

CREATE TABLE IF NOT EXISTS lesson_index (lesson_id TEXT, project_id TEXT, text TEXT);

CREATE INDEX IF NOT EXISTS lesson_index_terms ON lesson_index USING gin(to_tsvector('simple',text));

CREATE TABLE IF NOT EXISTS experience_entries (id TEXT PRIMARY KEY, version BIGINT NOT NULL, state TEXT NOT NULL,
  project_id TEXT NOT NULL, payload TEXT NOT NULL, record TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS experience_history (entry_id TEXT NOT NULL, version BIGINT NOT NULL,
  state TEXT NOT NULL, project_id TEXT NOT NULL, payload TEXT NOT NULL, record TEXT NOT NULL,
  PRIMARY KEY(entry_id,version));

CREATE TABLE IF NOT EXISTS experience_lesson_refs (entry_id TEXT NOT NULL REFERENCES experience_entries(id) DEFERRABLE INITIALLY IMMEDIATE,
  lesson_id TEXT NOT NULL, project_id TEXT NOT NULL, version BIGINT NOT NULL, hash TEXT NOT NULL,
  state TEXT NOT NULL, PRIMARY KEY(entry_id,lesson_id));

CREATE TABLE IF NOT EXISTS experience_index (entry_id TEXT, project_id TEXT, text TEXT);

CREATE INDEX IF NOT EXISTS experience_index_terms ON experience_index USING gin(to_tsvector('simple',text));

CREATE TABLE IF NOT EXISTS knowledge_plans (plan_id TEXT PRIMARY KEY, client TEXT NOT NULL,
  project_id TEXT NOT NULL, directory TEXT NOT NULL, body TEXT NOT NULL,
  issued_revision BIGINT NOT NULL, issued_at TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS knowledge_plans_scope ON knowledge_plans(client,project_id,directory);

CREATE TABLE IF NOT EXISTS research_notes (id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES knowledge_projects(id) DEFERRABLE INITIALLY IMMEDIATE, key TEXT NOT NULL,
  owner TEXT NOT NULL, version BIGINT NOT NULL, state TEXT NOT NULL, payload TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS research_notes_project ON research_notes(project_id,state,id);

CREATE TABLE IF NOT EXISTS research_note_history (note_id TEXT NOT NULL REFERENCES research_notes(id) DEFERRABLE INITIALLY IMMEDIATE,
  version BIGINT NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(note_id,version));

CREATE TABLE IF NOT EXISTS research_note_citations (note_id TEXT NOT NULL, version BIGINT NOT NULL,
  ordinal BIGINT NOT NULL, kind TEXT NOT NULL, block_id TEXT, document_id TEXT,
  document_version BIGINT, hash TEXT NOT NULL, cited_note_id TEXT, cited_note_version BIGINT,
  PRIMARY KEY(note_id,version,ordinal));

CREATE INDEX IF NOT EXISTS research_note_citations_source ON research_note_citations(document_id,document_version);

CREATE INDEX IF NOT EXISTS research_note_citations_note ON research_note_citations(cited_note_id);

CREATE TABLE IF NOT EXISTS research_note_index (note_id TEXT, project_id TEXT, text TEXT);

CREATE INDEX IF NOT EXISTS research_note_index_terms ON research_note_index USING gin(to_tsvector('simple',text));

CREATE TABLE IF NOT EXISTS automatic_facts (
 group_id TEXT PRIMARY KEY REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE, scope TEXT NOT NULL,
 fact_key TEXT NOT NULL, value_key TEXT NOT NULL, observed_at TEXT NOT NULL,
 payload TEXT NOT NULL, superseded_by TEXT REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE);

CREATE INDEX IF NOT EXISTS automatic_fact_identity ON automatic_facts(scope,fact_key,value_key);

CREATE TABLE IF NOT EXISTS automatic_evidence (
 group_id TEXT NOT NULL REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE, source_key TEXT NOT NULL REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE,
 quote TEXT NOT NULL, source_text TEXT, PRIMARY KEY(group_id,source_key,quote));

CREATE TABLE IF NOT EXISTS context_operations (
 service TEXT NOT NULL, scope TEXT NOT NULL, operation_id TEXT NOT NULL,
 digest TEXT NOT NULL, receipt TEXT NOT NULL, batch_ref TEXT, item_id TEXT NOT NULL,
 PRIMARY KEY(service,scope,operation_id));

CREATE INDEX IF NOT EXISTS context_batch_page ON context_operations(service,scope,batch_ref,operation_id);

CREATE TABLE IF NOT EXISTS context_applications (
 source_key TEXT NOT NULL REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE, revision BIGINT NOT NULL,
 scope TEXT NOT NULL, target_key TEXT NOT NULL, operation_id TEXT NOT NULL,
 digest TEXT NOT NULL, group_id TEXT REFERENCES groups(id) DEFERRABLE INITIALLY IMMEDIATE,
 PRIMARY KEY(source_key,revision,scope,target_key,operation_id));

CREATE INDEX IF NOT EXISTS context_application_content ON context_applications(scope,target_key,digest);

CREATE TABLE IF NOT EXISTS context_associations (
 id TEXT PRIMARY KEY, source_account TEXT NOT NULL, target_account TEXT NOT NULL,
 source_person TEXT NOT NULL REFERENCES people(id) DEFERRABLE INITIALLY IMMEDIATE, target_person TEXT NOT NULL REFERENCES people(id) DEFERRABLE INITIALLY IMMEDIATE,
 actor_id TEXT NOT NULL, scopes TEXT NOT NULL, source_binding BIGINT NOT NULL,
 target_binding BIGINT NOT NULL, state TEXT NOT NULL, version BIGINT NOT NULL,
 proof_ref TEXT NOT NULL UNIQUE);

CREATE INDEX IF NOT EXISTS context_association_source ON context_associations(actor_id,source_person,state,id);

CREATE INDEX IF NOT EXISTS context_association_target ON context_associations(actor_id,target_person,state,id);

CREATE TABLE IF NOT EXISTS context_identity_epochs (
 actor_id TEXT NOT NULL, person_id TEXT NOT NULL REFERENCES people(id) DEFERRABLE INITIALLY IMMEDIATE, version BIGINT NOT NULL,
 PRIMARY KEY(actor_id,person_id));

CREATE TABLE IF NOT EXISTS relationship_pairs (
 actor_id TEXT NOT NULL, person_id TEXT NOT NULL REFERENCES people(id) DEFERRABLE INITIALLY IMMEDIATE,
 relationship_type TEXT NOT NULL, display_label TEXT NOT NULL,
 score BIGINT NOT NULL, stage TEXT NOT NULL, frozen BIGINT NOT NULL,
 frozen_since TEXT, version BIGINT NOT NULL, policy TEXT NOT NULL,
 activity_at TEXT NOT NULL, decay_days BIGINT NOT NULL, decay_cursor TEXT NOT NULL,
 clock_head TEXT NOT NULL, ready BIGINT NOT NULL,
 PRIMARY KEY(actor_id,person_id)
);

CREATE TABLE IF NOT EXISTS relationship_events (
 event_id TEXT PRIMARY KEY, digest TEXT NOT NULL, actor_id TEXT NOT NULL,
 person_id TEXT NOT NULL, kind TEXT NOT NULL, delta BIGINT NOT NULL,
 outcome TEXT NOT NULL, settled_at TEXT NOT NULL, budget_day TEXT,
 result TEXT NOT NULL, valid BIGINT NOT NULL DEFAULT 1,
 FOREIGN KEY(actor_id,person_id) REFERENCES relationship_pairs(actor_id,person_id) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX IF NOT EXISTS relationship_event_page ON relationship_events(actor_id,person_id,settled_at,event_id);

CREATE INDEX IF NOT EXISTS relationship_daily_budget ON relationship_events(actor_id,person_id,budget_day);

CREATE TABLE IF NOT EXISTS relationship_sources (
 event_id TEXT NOT NULL REFERENCES relationship_events(event_id) DEFERRABLE INITIALLY IMMEDIATE,
 source_key TEXT NOT NULL REFERENCES sources(key) DEFERRABLE INITIALLY IMMEDIATE, revision BIGINT NOT NULL,
 epoch BIGINT NOT NULL, scope TEXT NOT NULL,
 PRIMARY KEY(event_id,source_key)
);

CREATE INDEX IF NOT EXISTS relationship_source_lookup ON relationship_sources(source_key,event_id);

CREATE TABLE IF NOT EXISTS relationship_commands (
 operator TEXT NOT NULL, request_id TEXT NOT NULL, digest TEXT NOT NULL,
 actor_id TEXT NOT NULL, person_id TEXT NOT NULL, result TEXT NOT NULL,
 PRIMARY KEY(operator,request_id),
 FOREIGN KEY(actor_id,person_id) REFERENCES relationship_pairs(actor_id,person_id) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE IF NOT EXISTS relationship_legacy (
 group_id TEXT PRIMARY KEY REFERENCES relationship_entries(group_id) DEFERRABLE INITIALLY IMMEDIATE,
 actor_id TEXT, person_id TEXT, amount BIGINT NOT NULL,
 state TEXT NOT NULL, reason TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS relationship_freezes (
 freeze_id TEXT PRIMARY KEY, actor_id TEXT NOT NULL, person_id TEXT NOT NULL,
 started_at TEXT NOT NULL, ended_at TEXT,
 FOREIGN KEY(actor_id,person_id) REFERENCES relationship_pairs(actor_id,person_id) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE UNIQUE INDEX IF NOT EXISTS relationship_active_freeze ON relationship_freezes(actor_id,person_id) WHERE ended_at IS NULL;

CREATE TABLE IF NOT EXISTS observation_sources (source_ref TEXT PRIMARY KEY, digest TEXT NOT NULL, instance_id TEXT NOT NULL, self_id TEXT NOT NULL, conversation TEXT NOT NULL, author TEXT NOT NULL, event_id TEXT NOT NULL, scope_version BIGINT NOT NULL, archive_epoch BIGINT NOT NULL, sent_at TEXT NOT NULL, content_state TEXT NOT NULL, text TEXT NOT NULL, mentioned BIGINT NOT NULL, state TEXT NOT NULL, received_at DOUBLE PRECISION NOT NULL, UNIQUE(instance_id,self_id,conversation,author,event_id));

CREATE INDEX IF NOT EXISTS observation_page ON observation_sources(instance_id,self_id,conversation,received_at,source_ref);

CREATE TABLE IF NOT EXISTS qq_aliases (account_key TEXT NOT NULL REFERENCES accounts(account_key) DEFERRABLE INITIALLY IMMEDIATE, kind TEXT NOT NULL, bot_id TEXT NOT NULL, group_id TEXT NOT NULL, value TEXT NOT NULL, observed_at TEXT NOT NULL, event_ref TEXT NOT NULL, PRIMARY KEY(account_key,kind,bot_id,group_id));

CREATE TABLE IF NOT EXISTS qq_alias_events (event_ref TEXT PRIMARY KEY,digest TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS profile_approval_authorities (ref TEXT PRIMARY KEY REFERENCES profile_approvals(ref) DEFERRABLE INITIALLY IMMEDIATE, authority TEXT NOT NULL, draft TEXT NOT NULL, revoked BIGINT NOT NULL DEFAULT 0);

